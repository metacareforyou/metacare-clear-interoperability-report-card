// Regenerate the tables in README.md from results/, triage/ and defects/.
// Only the text between the report-card markers is replaced; the prose around it is kept.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const START = '<!-- report-card:start (generated by scripts/import-run.mjs, do not edit by hand) -->';
const END = '<!-- report-card:end -->';

export function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

// Front matter of a defect file: "key: value" lines between two "---" lines.
export function readDefect(path) {
  const text = readFileSync(path, 'utf8');
  const match = text.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) throw new Error(`${path} has no front matter`);
  const meta = {};
  for (const line of match[1].split('\n')) {
    const at = line.indexOf(':');
    if (at > 0) meta[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }
  return meta;
}

export function listDefects(root) {
  const dir = join(root, 'defects');
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => /^[A-Z0-9-]+\.md$/.test(name))
    .map((name) => ({ file: `defects/${name}`, ...readDefect(join(dir, name)) }))
    .sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
}

function runsFor(root, kit) {
  const dir = join(root, 'results', kit);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => existsSync(join(dir, name, 'summary.json')))
    .sort()
    .map((date) => ({
      date,
      path: `results/${kit}/${date}`,
      summary: readJson(join(dir, date, 'summary.json')),
      results: readJson(join(dir, date, 'results.json')),
      run: readJson(join(dir, date, 'run.json'))
    }));
}

function triageFor(root, kit) {
  const path = join(root, 'triage', `${kit}.json`);
  return existsSync(path) ? readJson(path) : { failures: [], notRun: [] };
}

function matches(rule, test) {
  if (rule.match && !new RegExp(rule.match).test(test.id)) return false;
  if (rule.message && !new RegExp(rule.message).test(test.message || '')) return false;
  if (rule.result && rule.result !== test.result) return false;
  return true;
}

function owner(rule, defects) {
  const parts = [];
  for (const id of [].concat(rule.defect || [])) {
    const defect = defects.find((d) => d.id === id);
    parts.push(defect ? `[${id}](${defect.file})` : id);
  }
  for (const id of [].concat(rule.clear || [])) parts.push(`Clear ${id}`);
  if (rule.owner) parts.push(rule.owner);
  return parts.join(', ') || 'Not yet assigned';
}

function listTests(tests, limit = 10) {
  const ids = tests.map((t) => t.short_id);
  if (ids.length <= limit) return ids.join(', ');
  return `${ids.slice(0, limit).join(', ')} and ${ids.length - limit} more`;
}

function parentId(test) {
  return test.short_id.split('.').slice(0, -1).join('.');
}

function groupBy(items, keyOf) {
  const map = new Map();
  for (const item of items) {
    const key = keyOf(item);
    if (!map.has(key)) map.set(key, []);
    map.get(key).push(item);
  }
  return map;
}

function runTime(r) {
  return `${r.summary.generatedAt.slice(0, 16).replace('T', ' ')} UTC`;
}

function clearTested(run) {
  const c = run.clear;
  const prs = c.pullRequests.map((n) => `[#${n}](${c.repository}/pull/${n})`).join(', ');
  return `\`${c.branch}\` at \`${c.commit}\`${prs ? `, ${prs}` : ''}`;
}

function attestedByScript(test) {
  return typeof test.attestedBy === 'string' && test.attestedBy.startsWith('attested by script');
}

function renderKit(root, kitId, kit, defects) {
  const runs = runsFor(root, kitId);
  const out = [];
  out.push(`### ${kit.label}`);
  out.push('');
  out.push(`Kit [${kit.repository.replace('https://github.com/', '')}](${kit.repository}) ${kit.tag} \`${kit.commit.slice(0, 7)}\`, suite \`${kit.suite}\`, guide ${kit.ig}.`);
  if (kit.patch) {
    out.push('');
    out.push(`> **Patched kit: not a result of the official kit.** ${kit.patch.what} Patch: [${kit.patch.branch}](${kit.patch.repository}/tree/${kit.patch.branch}) at \`${kit.patch.commit}\` (image ${kit.patch.image}), the fix proposed in [${kit.patch.defect}](defects/${kit.patch.defect}.md). This run is evidence about that defect only. The official result for this guide and option is the row without "patched kit".`);
  }
  out.push('');
  if (!runs.length) {
    out.push('No run imported yet.');
    out.push('');
    return out;
  }
  const latest = runs[runs.length - 1];
  const tests = latest.results.filter((t) => t.kind === 'test');
  const triage = triageFor(root, kitId);
  const t = latest.summary.totals;

  out.push(`Latest run: ${runTime(latest)}, Clear ${clearTested(latest.run)}. [Results](${latest.path}/results.json), [summary](${latest.path}/summary.json).`);
  if (latest.run.clear.note) out.push(`${latest.run.clear.note}`);
  out.push('');

  // Failures and errors, grouped by cause.
  const failing = tests.filter((x) => x.result === 'fail' || x.result === 'error');
  if (failing.length) {
    out.push('Failures and errors:');
    out.push('');
    out.push('| Cause | Who fixes it | Result | Tests |');
    out.push('|---|---|---|---|');
    const byRule = groupBy(failing, (x) => triage.failures.findIndex((rule) => matches(rule, x)));
    for (const [index, group] of [...byRule.entries()].sort((a, b) => (a[0] === -1) - (b[0] === -1) || a[0] - b[0])) {
      const rule = index >= 0 ? triage.failures[index] : { cause: 'Not yet triaged.' };
      const results = [...new Set(group.map((x) => x.result))].join(', ');
      out.push(`| ${rule.cause} | ${index >= 0 ? owner(rule, defects) : 'Not yet assigned'} | ${results} | ${listTests(group)} |`);
    }
    out.push('');
  }

  // Not run and skipped, grouped by reason, listed by parent group.
  const idle = tests.filter((x) => x.result === 'not run' || x.result === 'skip' || x.result === 'omit');
  if (idle.length) {
    out.push('Not run, skipped or omitted:');
    out.push('');
    out.push('| Reason | Result | Count | Groups |');
    out.push('|---|---|---|---|');
    const byReason = groupBy(idle, (x) => {
      const index = triage.notRun.findIndex((rule) => matches(rule, x));
      return `${index}|${x.result}`;
    });
    for (const [key, group] of [...byReason.entries()].sort()) {
      const index = Number(key.split('|')[0]);
      const reason = index >= 0 ? triage.notRun[index].reason : 'No reason recorded yet.';
      const groups = [...new Set(group.map(parentId))];
      const shown = groups.length > 12 ? `${groups.slice(0, 12).join(', ')} and ${groups.length - 12} more` : groups.join(', ');
      out.push(`| ${reason} | ${group[0].result} | ${group.length} | ${shown} |`);
    }
    out.push('');
  }

  // Waits released by the run script.
  const attested = tests.filter(attestedByScript);
  const released = tests.filter((x) => x.attestedBy && !attestedByScript(x));
  out.push(`Released by script: ${attested.length} attestation(s) and ${released.length} wait(s) in which Clear was told to send its requests.`);
  if (attested.length) {
    out.push('The attestations below were released from Clear\'s recorded state. They are not observed conformance, and a person must confirm them in the Inferno interface before results are submitted.');
    out.push('');
    out.push('| Test | Title | Result |');
    out.push('|---|---|---|');
    for (const x of attested) out.push(`| ${x.short_id} | ${x.title} | ${x.result} |`);
  }
  out.push('');

  if (runs.length > 1) {
    out.push('Earlier runs:');
    out.push('');
    for (const r of runs.slice(0, -1).reverse()) {
      const rt = r.summary.totals;
      out.push(`- ${runTime(r)}: ${rt.pass} pass, ${rt.fail} fail, Clear ${clearTested(r.run)} ([results](${r.path}/results.json))`);
    }
    out.push('');
  }
  return out;
}

function overview(root, kits, patched = false) {
  const out = [];
  out.push('| Guide | Suite | Run date | Clear tested | Tests | Pass | Fail | Error | Skip | Not run | Attested by script |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const kitId of Object.keys(kits).filter((id) => Boolean(kits[id].patch) === patched)) {
    const kit = kits[kitId];
    const runs = runsFor(root, kitId);
    if (!runs.length) {
      out.push(`| ${kit.label} | \`${kit.suite}\` | not run | | | | | | | | |`);
      continue;
    }
    const latest = runs[runs.length - 1];
    const t = latest.summary.totals;
    const attested = latest.results.filter((x) => x.kind === 'test' && attestedByScript(x)).length;
    out.push(`| ${kit.label} | \`${kit.suite}\` | ${runTime(latest)} | ${clearTested(latest.run)} | ${t.tests} | ${t.pass} | ${t.fail} | ${t.error ?? 0} | ${t.skip ?? 0} | ${t.notRun ?? 0} | ${attested} |`);
  }
  return out;
}

function defectTable(defects) {
  const out = [];
  out.push('| Id | Where the defect is | Summary | Status | Fix |');
  out.push('|---|---|---|---|---|');
  for (const d of defects) {
    const fix = d.fork_branch && d.fork_branch !== 'none' ? `[${d.fork_branch.split('/tree/')[1] || 'branch'}](${d.fork_branch})` : 'proposed in the draft';
    const status = d.filed_url ? `[${d.status}](${d.filed_url})` : d.status;
    out.push(`| [${d.id}](${d.file}) | ${d.target}${d.also_report ? `; also ${d.also_report}` : ''} | ${d.title} | ${status} | ${fix} |`);
  }
  return out;
}

export function renderReadme(root) {
  const kits = readJson(join(root, 'kits.json')).kits;
  const defects = listDefects(root);
  const body = [START, '', '## Summary', '', 'Runs of the unmodified kits at their pinned commits. These are the results.', '', ...overview(root, kits), ''];
  if (Object.values(kits).some((k) => k.patch)) {
    body.push('### Evidence runs with a patched kit', '');
    body.push('Each of these ran a kit with one MetaCare fix for a drafted defect. They show whether that defect is the only cause of the official failures. They are not results of the official kit.', '');
    body.push(...overview(root, kits, true), '');
  }
  body.push('## Results by guide', '');
  for (const kitId of Object.keys(kits)) body.push(...renderKit(root, kitId, kits[kitId], defects));
  body.push('## Defects found in test kits and guides', '');
  body.push(...defectTable(defects), '', END);

  const path = join(root, 'README.md');
  const current = readFileSync(path, 'utf8');
  const start = current.indexOf(START);
  const end = current.indexOf(END);
  if (start < 0 || end < 0) throw new Error('README.md has no report-card markers');
  writeFileSync(path, current.slice(0, start) + body.join('\n') + current.slice(end + END.length));
}
